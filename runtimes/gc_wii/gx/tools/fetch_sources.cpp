// mpt_fetch_sources: fetch and verify every entry of a source lock with asset-import's resolver
// (ADR 0009 section 1 and the amendment after the P1-14 gate), for the GX layer's host
// dependencies: runtimes/gc_wii/gx/aurora.lock and dawn.lock.
//
//   mpt_fetch_sources --lock <file> --cache <dir> [--override name=<dir>]... [--out <file.cmake>]
//
// Each source is cloned by URL, checked out at the locked commit, and checked against the lock's
// commit and tree. For dawn.lock the DEPS file is cross-checked against `deps`/`skipped_deps`.
// Dawn's fetch_dawn_dependencies.py is never run.
//
// --out writes a CMake script with one line per source:
//   set(MPT_SOURCE_<name>_DIR "<dir>")  and  set(MPT_SOURCE_<name>_PINNED TRUE|FALSE)
// which build_dawn.cmake and runtimes/gc_wii/gx/CMakeLists.txt include.
#include <filesystem>
#include <fstream>
#include <iostream>
#include <map>
#include <string>

#include "mpt/asset_import/process.h"
#include "mpt/asset_import/source_lock.h"
#include "mpt/asset_import/sources.h"

namespace fs = std::filesystem;
namespace ai = mpt::asset_import;

namespace {

int usage() {
  std::cerr << "usage: mpt_fetch_sources --lock <file> --cache <dir> [--override name=<dir>]... [--out <file.cmake>]\n";
  return 2;
}

std::string cmake_path(const fs::path& p) {
  const std::u8string u = p.generic_u8string();
  const std::string s(reinterpret_cast<const char*>(u.data()), u.size());
  std::string out;
  for (char c : s) {
    if (c == '"' || c == '\\' || c == '$') out.push_back('\\');
    out.push_back(c);
  }
  return out;
}

}  // namespace

int main(int argc, char** argv) {
  fs::path lock_path;
  fs::path cache;
  fs::path out_path;
  std::map<std::string, ai::SourceInput> inputs;
  for (int i = 1; i < argc; ++i) {
    const std::string arg = argv[i];
    const bool has_value = i + 1 < argc;
    if (arg == "--lock" && has_value) {
      lock_path = fs::u8path(argv[++i]);
    } else if (arg == "--cache" && has_value) {
      cache = fs::u8path(argv[++i]);
    } else if (arg == "--out" && has_value) {
      out_path = fs::u8path(argv[++i]);
    } else if (arg == "--override" && has_value) {
      const std::string value = argv[++i];
      const auto eq = value.find('=');
      if (eq == std::string::npos || eq == 0) return usage();
      inputs[value.substr(0, eq)] = ai::SourceInput{ai::SourceOrigin::override_dir, fs::u8path(value.substr(eq + 1))};
    } else {
      return usage();
    }
  }
  if (lock_path.empty() || cache.empty()) return usage();

  std::string error;
  const auto lock = ai::SourceLock::load(lock_path, error);
  if (!lock) {
    std::cerr << "mpt_fetch_sources: " << error << "\n";
    return 1;
  }
  ai::SystemProcessRunner runner;
  ai::SourceResolver resolver(cache, runner);
  const auto resolved = resolver.resolve_all(*lock, inputs, error);
  if (!resolved) {
    std::cerr << "mpt_fetch_sources: " << error << "\n";
    return 1;
  }

  std::ofstream out;
  if (!out_path.empty()) {
    out.open(out_path, std::ios::binary | std::ios::trunc);
    if (!out) {
      std::cerr << "mpt_fetch_sources: cannot write " << out_path.string() << "\n";
      return 1;
    }
    out << "# Generated by mpt_fetch_sources from " << cmake_path(lock_path.filename()) << ". Do not edit.\n";
  }
  for (const auto& [name, source] : *resolved) {
    std::cout << name << "\t" << ai::to_string(source.origin) << "\t" << (source.pinned ? "pinned" : "UNPINNED")
              << "\t" << source.actual << "\t" << source.dir.string() << "\n";
    if (out) {
      out << "set(MPT_SOURCE_" << name << "_DIR \"" << cmake_path(source.dir) << "\")\n";
      out << "set(MPT_SOURCE_" << name << "_PINNED " << (source.pinned ? "TRUE" : "FALSE") << ")\n";
      out << "set(MPT_SOURCE_" << name << "_COMMIT \"" << source.commit << "\")\n";
    }
  }
  return 0;
}
